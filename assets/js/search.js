/* Site search: the magnifier in the header opens a full-screen search over
   products, categories and pages (index in search-index.js, generated by
   tools/build_site.py). Matching ignores accents and tolerates small typos. */
(() => {
  const btn = document.getElementById('searchBtn');
  const index = window.SEARCH_INDEX || [];
  if (!btn || !index.length) return;

  const self = document.querySelector('script[src$="assets/js/search.js"]');
  const root = self ? self.getAttribute('src').replace(/assets\/js\/search\.js$/, '') : '';
  const dict = () => {
    let c = 'EN';
    try { c = localStorage.getItem('codutti_lang') || 'EN'; } catch (e) {}
    return (window.I18N && (window.I18N[c] || window.I18N.EN)) || {};
  };
  const t = (k, fb) => dict()[k] || fb;
  const norm = (s) => (s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9Ѐ-ӿ؀-ۿ ]+/g, ' ').trim();

  const lev = (a, b, max) => {
    if (Math.abs(a.length - b.length) > max) return max + 1;
    let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
    for (let i = 1; i <= a.length; i++) {
      const cur = [i];
      let best = i;
      for (let j = 1; j <= b.length; j++) {
        cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
        best = Math.min(best, cur[j]);
      }
      if (best > max) return max + 1;
      prev = cur;
    }
    return prev[b.length];
  };

  const prepared = index.map((e) => ({ e, words: norm(e.t + ' ' + e.s + ' ' + e.x).split(/\s+/).filter(Boolean), title: norm(e.t) }));

  const score = (p, terms) => {
    let total = 0;
    for (const q of terms) {
      let best = 0;
      for (const w of p.words) {
        if (w === q) { best = 3; break; }
        if (w.startsWith(q)) best = Math.max(best, 2);
        else if (q.length >= 4 && lev(q, w.slice(0, q.length + 1), 1) <= 1) best = Math.max(best, 1);
      }
      if (!best) return 0;
      total += best;
    }
    if (p.title.startsWith(terms.join(' '))) total += 3;
    return total;
  };

  const el = document.createElement('div');
  el.className = 'search-overlay';
  el.setAttribute('role', 'dialog');
  el.setAttribute('aria-modal', 'true');
  el.innerHTML = `
    <div class="search-overlay__bar">
      <svg viewBox="0 0 24 24" aria-hidden="true"><circle cx="10.5" cy="10.5" r="6"/><path d="M15 15l5 5"/></svg>
      <input class="search-overlay__input" type="search" autocomplete="off" spellcheck="false">
      <button type="button" class="search-overlay__close" aria-label="Close">&times;</button>
    </div>
    <div class="search-overlay__results" aria-live="polite"></div>`;
  document.body.appendChild(el);
  const input = el.querySelector('input');
  const results = el.querySelector('.search-overlay__results');

  const render = () => {
    const terms = norm(input.value).split(/\s+/).filter(Boolean);
    results.innerHTML = '';
    if (!terms.length) return;
    const hits = prepared.map((p) => ({ p, s: score(p, terms) })).filter((h) => h.s > 0)
      .sort((a, b) => b.s - a.s).slice(0, 40);
    if (!hits.length) {
      results.innerHTML = `<p class="search-overlay__empty">${t('search.empty', 'No results. Try another word.')}</p>`;
      return;
    }
    const groups = [['p', t('search.products', 'Products')], ['c', t('search.categories', 'Categories')], ['g', t('search.pages', 'Pages')]];
    groups.forEach(([k, label]) => {
      const g = hits.filter((h) => h.p.e.k === k);
      if (!g.length) return;
      const h = document.createElement('p');
      h.className = 'search-overlay__group';
      h.textContent = label;
      results.appendChild(h);
      g.forEach(({ p }) => {
        const a = document.createElement('a');
        a.className = 'search-hit';
        a.href = root + p.e.u;
        a.innerHTML = (p.e.i ? `<span class="search-hit__img"><img class="fit-${p.e.f || 'contain'}" src="${root + p.e.i}" alt="" loading="lazy"></span>` : '')
          + `<span><span class="search-hit__t"></span><br><span class="search-hit__s"></span></span>`;
        a.querySelector('.search-hit__t').textContent = p.e.t;
        a.querySelector('.search-hit__s').textContent = p.e.s;
        results.appendChild(a);
      });
    });
  };

  const open = () => {
    input.placeholder = '';
    input.setAttribute('aria-label', t('search.open', 'Search'));
    el.querySelector('.search-overlay__close').setAttribute('aria-label', t('prod.close', 'Close'));
    el.classList.add('is-open');
    document.body.classList.add('search-open');
    setTimeout(() => input.focus(), 50);
  };
  const close = () => {
    el.classList.remove('is-open');
    document.body.classList.remove('search-open');
    btn.focus();
  };
  btn.addEventListener('click', open);
  el.querySelector('.search-overlay__close').addEventListener('click', close);
  el.addEventListener('keydown', (e) => { if (e.key === 'Escape') close(); });
  let timer;
  input.addEventListener('input', () => { clearTimeout(timer); timer = setTimeout(render, 80); });
  document.addEventListener('keydown', (e) => {
    if ((e.key === '/' && !/input|textarea/i.test(document.activeElement.tagName)) || ((e.metaKey || e.ctrlKey) && e.key === 'k')) {
      e.preventDefault(); open();
    }
  });
})();
